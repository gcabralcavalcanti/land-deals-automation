"""The Excel workbook: assumptions, parcels, costs, cash flow, scenarios, sensitivity, strategy and memos."""
from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from . import config
from .model import CATEGORIES

MONEY, PCT, INT = '"R$" #,##0;[Red]-"R$" #,##0', "0.0%", "#,##0"
HEAD = PatternFill("solid", fgColor="1F4E5F")


def month_label(m: int) -> str:
    y, mo = config.START
    k = mo - 1 + m
    return f"{y + k // 12}-{k % 12 + 1:02d}"


def _table(ws, headers, rows, formats=None, row=1, col=1, widths=None):
    for j, h in enumerate(headers):
        c = ws.cell(row, col + j, h)
        c.font, c.fill = Font(bold=True, color="FFFFFF"), HEAD
        c.alignment = Alignment(wrap_text=True, vertical="top")
    for i, r in enumerate(rows, start=row + 1):
        for j, v in enumerate(r):
            c = ws.cell(i, col + j, v)
            if formats and formats.get(j + 1) and v is not None:
                c.number_format = formats[j + 1]
    for j, h in enumerate(headers):
        w = (widths or {}).get(j + 1) or min(max([len(str(h))] + [len(f"{r[j]:,.0f}" if isinstance(r[j], float)
                                                                     else str(r[j])) for r in rows if r[j] is not None]) + 3, 48)
        ws.column_dimensions[get_column_letter(col + j)].width = max(w, 10)


def build(path: Path, parcels: list[dict], pf: dict, scen: list[dict], sens: list[dict], strat: list[dict],
          memos: list[dict]) -> Path:
    wb = Workbook()
    _summary(wb.active, pf, scen)
    _assumptions(wb.create_sheet("Assumptions"))
    _parcels(wb.create_sheet("Parcels"), parcels, pf)
    _costs(wb.create_sheet("Costs"), pf)
    _cash(wb.create_sheet("Cash flow"), pf)
    _sensitivity(wb.create_sheet("Sensitivity"), sens)
    _strategy(wb.create_sheet("Strategy"), strat)
    _memos(wb.create_sheet("Memos"), memos)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


def _summary(ws, pf, scen):
    ws.title = "Summary"
    ws["A1"] = "Land portfolio - cost x return"
    ws["A1"].font = Font(bold=True, size=14)
    ws["A2"] = "Synthetic data generated by generate_data.py. Assumptions and their sources: sheet Assumptions."
    k = [("Parcels", len(pf["projects"]), INT), ("VGV (total sales value)", pf["vgv"], MONEY),
         ("  of which subdivision", pf["vgv_by_strategy"]["subdivision"], MONEY),
         ("  of which whole-lot resale", pf["vgv_by_strategy"]["whole"], MONEY),
         ("Net profit (nominal)", pf["profit"], MONEY), ("Margin on VGV", pf["margin"], PCT),
         (f"NPV at {config.base()['discount_rate_year']:.0%} a year", pf["npv"], MONEY), ("IRR (per year)", pf["irr"], PCT),
         ("Maximum cash exposure", pf["max_exposure"], MONEY), ("Month of maximum exposure", month_label(pf["exposure_month"]), None),
         ("Payback month", month_label(pf["payback_month"]) if pf["payback_month"] is not None else "not reached", None)]
    _table(ws, ["Portfolio KPI", "Value"], [[a, b] for a, b, _ in k], row=4, widths={1: 34, 2: 18})
    for i, (_, _, f) in enumerate(k, start=5):
        if f:
            ws.cell(i, 2).number_format = f
    _table(ws, ["Scenario", "VGV", "Profit", "NPV", "IRR", "Max exposure", "Margin"],
           [[s["scenario"], s["vgv"], s["profit"], s["npv"], s["irr"], s["max_exposure"], s["margin"]] for s in scen],
           {2: MONEY, 3: MONEY, 4: MONEY, 5: PCT, 6: MONEY, 7: PCT}, row=18)
    ws.cell(22, 1, "Pessimistic: lot prices -15%, slower sales (48 months), infrastructure R$ 160/m2, longer holding, "
                   "lower appreciation, 3% default. Optimistic: the opposite ends of each range.")
    # cumulative cash chart from the Cash flow sheet is added there; here a scenario NPV chart
    ch = BarChart()
    ch.title, ch.y_axis.title = "Portfolio NPV by scenario", "R$"
    ch.add_data(Reference(ws, min_col=4, min_row=18, max_row=21), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=19, max_row=21))
    ch.height, ch.width = 7, 14
    ws.add_chart(ch, "D3")


def _assumptions(ws):
    rows = [[k, v[0], v[1], v[2], v[3], v[4]] for k, v in config.ASSUMPTIONS.items()]
    _table(ws, ["Assumption", "Base", "Low", "High", "Unit", "Source"], rows, widths={1: 26, 5: 30, 6: 90})


def _parcels(ws, parcels, pf):
    by_id = {p["id"]: p for p in pf["projects"]}
    rows = []
    for p in parcels:
        r = by_id[p["id"]]
        rows.append([p["id"], p["name"], p["kind"], p["town"], p["area_m2"], p["acquisition_price"],
                     month_label(p["acquisition_month"]), r["strategy"], r["lots"], r["vgv"], r["profit"], r["margin"],
                     r["npv"], r["irr"], r["max_exposure"], r["payback_months"], r["roi_year"]])
    _table(ws, ["Id", "Parcel", "Kind", "Town", "Area m2", "Acquisition", "Bought", "Strategy", "Lots", "VGV",
                "Profit", "Margin", "NPV", "IRR", "Max exposure", "Payback (months)", "ROI per year"], rows,
           {5: INT, 6: MONEY, 9: INT, 10: MONEY, 11: MONEY, 12: PCT, 13: MONEY, 14: PCT, 15: MONEY, 16: INT, 17: PCT})
    ws.freeze_panes = "C2"
    n = len(rows)
    ch = BarChart()
    ch.title, ch.y_axis.title = "NPV by parcel", "R$"
    ch.add_data(Reference(ws, min_col=13, min_row=1, max_row=n + 1), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=2, max_row=n + 1))
    ch.height, ch.width = 8, 18
    ws.add_chart(ch, f"B{n + 4}")


def _costs(ws, pf):
    cats = list(CATEGORIES)
    rows = [[p["id"], p["name"]] + [p["totals"][c] for c in cats] + [p["profit"]] for p in pf["projects"]]
    rows.append(["Total", ""] + [sum(p["totals"][c] for p in pf["projects"]) for c in cats] + [pf["profit"]])
    _table(ws, ["Id", "Parcel"] + [c.replace("_", " ") for c in cats] + ["Net profit"], rows,
           {j: MONEY for j in range(3, len(cats) + 4)})
    ws.cell(len(rows) + 3, 1, "Outflows are negative. Installments are net of the default assumption.")


def _cash(ws, pf):
    cats = list(CATEGORIES)
    rows = [[month_label(m)] + [pf["by_category"][c][i] for c in cats] + [pf["net"][i], pf["cumulative"][i]]
            for i, m in enumerate(pf["months"])]
    _table(ws, ["Month"] + [c.replace("_", " ") for c in cats] + ["Net", "Cumulative"], rows,
           {j: MONEY for j in range(2, len(cats) + 4)})
    ws.freeze_panes = "B2"
    n, col_net = len(rows), len(cats) + 2
    bars = BarChart()
    bars.title = "Portfolio cash flow: monthly net (bars) and cumulative (line)"
    bars.add_data(Reference(ws, min_col=col_net, min_row=1, max_row=n + 1), titles_from_data=True)
    bars.set_categories(Reference(ws, min_col=1, min_row=2, max_row=n + 1))
    line = LineChart()
    line.add_data(Reference(ws, min_col=col_net + 1, min_row=1, max_row=n + 1), titles_from_data=True)
    line.y_axis.axId = 200
    line.y_axis.crosses = "max"
    bars += line
    bars.height, bars.width = 10, 28
    ws.add_chart(bars, f"{get_column_letter(col_net + 3)}2")


def _sensitivity(ws, sens):
    rows = [[s["assumption"], s["low"], s["high"], s["npv_low"], s["npv_high"], s["npv_low"] - s["base_npv"],
             s["npv_high"] - s["base_npv"]] for s in sens]
    _table(ws, ["Assumption", "Low value", "High value", "NPV at low", "NPV at high", "Change at low", "Change at high"],
           rows, {4: MONEY, 5: MONEY, 6: MONEY, 7: MONEY})
    ws.cell(len(rows) + 3, 1, f"Base portfolio NPV: {sens[0]['base_npv']:,.0f}. One assumption moves at a time.")
    ch = BarChart()
    ch.type, ch.grouping, ch.overlap = "bar", "clustered", 100
    ch.title = "Tornado: change in portfolio NPV"
    ch.add_data(Reference(ws, min_col=6, max_col=7, min_row=1, max_row=len(rows) + 1), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=2, max_row=len(rows) + 1))
    ch.height, ch.width = 9, 18
    ws.add_chart(ch, "I2")


def _strategy(ws, strat):
    rows = [[s["id"], s["name"], s["area_m2"], s["rule"], s["vgv_subdivision"], s["npv_subdivision"],
             s["irr_subdivision"], s["vgv_whole"], s["npv_whole"], s["irr_whole"]] for s in strat]
    _table(ws, ["Id", "Parcel", "Area m2", "Rule picks", "VGV subdivided", "NPV subdivided", "IRR subdivided",
                "VGV sold whole", "NPV sold whole", "IRR sold whole"], rows,
           {3: INT, 5: MONEY, 6: MONEY, 7: PCT, 8: MONEY, 9: MONEY, 10: PCT})
    ws.cell(len(rows) + 3, 1, f"Rule: urban or urban-expansion parcels of at least "
                              f"{config.base()['subdivision_min_m2']:,} m2 are subdivided; the rest are sold whole.")


def _memos(ws, memos):
    rows = [[m["id"], m.get("recommendation", ""), m["status"], m.get("headline", ""), m.get("thesis", ""),
             " | ".join(m.get("risks", [])), " | ".join(m.get("conditions", []))] for m in memos]
    _table(ws, ["Id", "Recommendation", "Number check", "Headline", "Thesis", "Risks", "Conditions"], rows,
           widths={4: 50, 5: 80, 6: 60, 7: 50})
    for i in range(2, len(rows) + 2):
        for j in (4, 5, 6, 7):
            ws.cell(i, j).alignment = Alignment(wrap_text=True, vertical="top")
