"""The Excel workbook: summary, assumptions, parcels, costs, cash flow, sensitivity, strategy and memos."""
from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from . import config
from .model import CATEGORIES

MONEY, PCT, INT = '"R$" #,##0;[Red]-"R$" #,##0', "0.0%", "#,##0"
AXIS_MI = '"R$" #,##0.0,," mi"'          # axis in R$ millions
HEAD = PatternFill("solid", fgColor="1F4E5F")
BLUE = "1F4E5F"


def month_label(m: int) -> str:
    y, mo = config.START
    k = mo - 1 + m
    return f"{y + k // 12}-{k % 12 + 1:02d}"


def _table(ws, headers, rows, formats=None, row=1, col=1, widths=None, freeze=True):
    for j, h in enumerate(headers):
        c = ws.cell(row, col + j, h)
        c.font, c.fill = Font(bold=True, color="FFFFFF"), HEAD
        c.alignment = Alignment(wrap_text=True, vertical="center")
    for i, r in enumerate(rows, start=row + 1):
        for j, v in enumerate(r):
            c = ws.cell(i, col + j, v)
            if formats and formats.get(j + 1) and v is not None:
                c.number_format = formats[j + 1]
    for j, h in enumerate(headers):
        w = (widths or {}).get(j + 1) or min(max([len(str(h))] + [len(f"{r[j]:,.0f}" if isinstance(r[j], float)
                                                                     else str(r[j])) for r in rows if r[j] is not None]) + 3, 48)
        ws.column_dimensions[get_column_letter(col + j)].width = max(w, 11)
    ws.row_dimensions[row].height = 30
    if freeze:
        ws.freeze_panes = ws.cell(row + 1, col + 1)


def _chart(kind, title: str, y_title: str, x_title: str = "", y_fmt: str | None = AXIS_MI, w=18, h=8):
    ch = kind()
    ch.title, ch.y_axis.title, ch.x_axis.title = title, y_title, x_title or None
    ch.height, ch.width = h, w
    ch.x_axis.delete = ch.y_axis.delete = False      # recent Excel hides openpyxl axes unless told otherwise
    if y_fmt:
        ch.y_axis.number_format = y_fmt
    ch.legend.position = "b"
    return ch


def build(path: Path, parcels: list[dict], pf: dict, scen: list[dict], sens: list[dict], strat: list[dict],
          memos: list[dict], findings: list[str] | None = None) -> Path:
    wb = Workbook()
    rec = {m["id"]: (m.get("recommendation") or "-").replace("_", " ") for m in memos}
    _summary(wb.active, pf, scen, findings or [])
    _quarterly(wb.create_sheet("Cash flow (quarterly)"), pf)
    _parcels(wb.create_sheet("Parcels"), parcels, pf, rec)
    _assumptions(wb.create_sheet("Assumptions"))
    _costs(wb.create_sheet("Costs"), pf)
    _cash(wb.create_sheet("Cash flow (monthly)"), pf)
    _sensitivity(wb.create_sheet("Sensitivity"), sens)
    _strategy(wb.create_sheet("Strategy"), strat)
    _memos(wb.create_sheet("Memos"), memos)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


def _summary(ws, pf, scen, findings):
    ws.title = "Summary"
    ws.sheet_view.showGridLines = False
    ws["A1"] = "Land portfolio - cost x return"
    ws["A1"].font = Font(bold=True, size=15, color=BLUE)
    ws["A2"] = "Synthetic data generated by generate_data.py. Assumptions and their sources: sheet Assumptions."
    ws["A2"].font = Font(italic=True, color="5B6A72")
    hurdle = config.base()["discount_rate_year"]
    k = [("Parcels", len(pf["projects"]), INT), ("VGV (total sales value)", pf["vgv"], MONEY),
         ("  subdivided", pf["vgv_by_strategy"]["subdivision"], MONEY),
         ("  sold whole", pf["vgv_by_strategy"]["whole"], MONEY),
         ("Net profit (nominal)", pf["profit"], MONEY), ("Margin on VGV", pf["margin"], PCT),
         (f"NPV at {hurdle:.0%} a year", pf["npv"], MONEY), ("IRR per year", pf["irr"], PCT),
         ("Maximum cash exposure", pf["max_exposure"], MONEY), ("Month of maximum exposure", month_label(pf["exposure_month"]), None),
         ("Payback month", month_label(pf["payback_month"]) if pf["payback_month"] is not None else "not reached", None)]
    _table(ws, ["Portfolio KPI", "Base case"], [[a, b] for a, b, _ in k], row=4, widths={1: 32, 2: 20}, freeze=False)
    for i, (_, _, f) in enumerate(k, start=5):
        ws.cell(i, 2).alignment = Alignment(horizontal="right")
        if f:
            ws.cell(i, 2).number_format = f
    _table(ws, ["Scenario", "VGV", "Profit", "NPV", "IRR", "Max exposure", "Margin"],
           [[s["scenario"], s["vgv"], s["profit"], s["npv"], s["irr"], s["max_exposure"], s["margin"]] for s in scen],
           {2: MONEY, 3: MONEY, 4: MONEY, 5: PCT, 6: MONEY, 7: PCT}, row=17, widths={1: 32, 2: 20}, freeze=False)
    ws.cell(21, 1, "Pessimistic and optimistic move lot prices, sales speed, infrastructure cost, holding time, "
                   "appreciation and default to the ends of their ranges (sheet Assumptions).").font = Font(italic=True, color="5B6A72")
    ws.cell(23, 1, "What the numbers say").font = Font(bold=True, size=12, color=BLUE)
    for i, f in enumerate(findings, start=24):
        ws.cell(i, 1, f"- {f}")
    ch = _chart(BarChart, "Portfolio NPV by scenario", "NPV (R$ million)", w=13, h=7.5)
    ch.add_data(Reference(ws, min_col=4, min_row=17, max_row=20), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=18, max_row=20))
    ch.legend = None
    ws.add_chart(ch, "D4")


def _quarterly(ws, pf):
    from .charts import _quarters
    labels, net, cum = _quarters(pf)
    _table(ws, ["Quarter", "Net cash (R$ million)", "Cumulative (R$ million)"],
           [[q, n, c] for q, n, c in zip(labels, net, cum)], {2: "#,##0.00", 3: "#,##0.00"}, widths={2: 22, 3: 24})
    n = len(labels)
    bars = _chart(BarChart, "Portfolio cash flow by quarter", "R$ million", "Quarter", y_fmt="#,##0", w=26, h=10)
    bars.add_data(Reference(ws, min_col=2, min_row=1, max_row=n + 1), titles_from_data=True)
    bars.set_categories(Reference(ws, min_col=1, min_row=2, max_row=n + 1))
    line = LineChart()
    line.add_data(Reference(ws, min_col=3, min_row=1, max_row=n + 1), titles_from_data=True)
    bars += line
    ws.add_chart(bars, "E2")


def _assumptions(ws):
    rows = [[k, v[0], v[1], v[2], v[3], v[4]] for k, v in config.ASSUMPTIONS.items()]
    _table(ws, ["Assumption", "Base", "Low", "High", "Unit", "Source"], rows, widths={1: 30, 2: 12, 3: 12, 4: 12, 5: 34, 6: 110})
    for i in range(2, len(rows) + 2):
        ws.cell(i, 6).alignment = Alignment(wrap_text=True, vertical="top")


def _parcels(ws, parcels, pf, rec):
    by_id = {p["id"]: p for p in pf["projects"]}
    rows = []
    for p in parcels:
        r = by_id[p["id"]]
        rows.append([p["id"], p["name"], p["kind"], p["town"], p["area_m2"], p["acquisition_price"],
                     month_label(p["acquisition_month"]), r["strategy"], r["lots"], r["vgv"], r["profit"], r["margin"],
                     r["npv"], r["irr"], r["max_exposure"], r["payback_months"], r["roi_year"], rec.get(p["id"], "-")])
    _table(ws, ["Id", "Parcel", "Kind", "Town", "Area m2", "Acquisition", "Bought", "Strategy", "Lots", "VGV",
                "Profit", "Margin", "NPV", "IRR", "Max exposure", "Payback (months)", "ROI per year", "AI memo"], rows,
           {5: INT, 6: MONEY, 9: INT, 10: MONEY, 11: MONEY, 12: PCT, 13: MONEY, 14: PCT, 15: MONEY, 16: INT, 17: PCT},
           widths={2: 26, 4: 28, 18: 22})
    ws.freeze_panes = "C2"
    n = len(rows)
    ch = _chart(BarChart, "NPV by parcel", "NPV (R$ million)", "Parcel")
    ch.add_data(Reference(ws, min_col=13, min_row=1, max_row=n + 1), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=2, max_row=n + 1))
    ch.legend = None
    ws.add_chart(ch, f"B{n + 4}")


def _costs(ws, pf):
    cats = list(CATEGORIES)
    rows = [[p["id"], p["name"]] + [p["totals"][c] for c in cats] + [p["profit"]] for p in pf["projects"]]
    rows.append(["Total", ""] + [sum(p["totals"][c] for p in pf["projects"]) for c in cats] + [pf["profit"]])
    _table(ws, ["Id", "Parcel"] + [c.replace("_", " ").capitalize() for c in cats] + ["Net profit"], rows,
           {j: MONEY for j in range(3, len(cats) + 4)}, widths={2: 26})
    last = len(rows) + 1
    for j in range(1, len(cats) + 4):
        ws.cell(last, j).font = Font(bold=True)
    ws.cell(last + 2, 1, "Outflows are negative. Installments are net of the default assumption. Nominal values.")


def _cash(ws, pf):
    cats = list(CATEGORIES)
    rows = [[month_label(m)] + [pf["by_category"][c][i] for c in cats] + [pf["net"][i], pf["cumulative"][i]]
            for i, m in enumerate(pf["months"])]
    _table(ws, ["Month"] + [c.replace("_", " ").capitalize() for c in cats] + ["Net", "Cumulative"], rows,
           {j: MONEY for j in range(2, len(cats) + 4)})


def _sensitivity(ws, sens):
    from .findings import label, value
    rows = [[label(s["assumption"]), value(s["assumption"], s["low"]), value(s["assumption"], s["high"]),
             s["npv_low"], s["npv_high"], s["npv_low"] - s["base_npv"], s["npv_high"] - s["base_npv"]] for s in sens]
    _table(ws, ["Assumption", "Low value", "High value", "NPV at low", "NPV at high", "Change at low", "Change at high"],
           rows, {4: MONEY, 5: MONEY, 6: MONEY, 7: MONEY}, widths={1: 30})
    ws.cell(len(rows) + 3, 1, f"Base portfolio NPV: R$ {sens[0]['base_npv']:,.0f}. One assumption moves at a time.")
    ch = _chart(BarChart, "Sensitivity: change in portfolio NPV", "Change in NPV (R$ million)")
    ch.type, ch.grouping, ch.overlap = "bar", "clustered", 100
    ch.add_data(Reference(ws, min_col=6, max_col=7, min_row=1, max_row=len(rows) + 1), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=2, max_row=len(rows) + 1))
    ws.add_chart(ch, "I2")


def _strategy(ws, strat):
    rows = [[s["id"], s["name"], s["area_m2"], s["rule"], s["vgv_subdivision"], s["npv_subdivision"],
             s["irr_subdivision"], s["vgv_whole"], s["npv_whole"], s["irr_whole"]] for s in strat]
    _table(ws, ["Id", "Parcel", "Area m2", "Rule picks", "VGV subdivided", "NPV subdivided", "IRR subdivided",
                "VGV sold whole", "NPV sold whole", "IRR sold whole"], rows,
           {3: INT, 5: MONEY, 6: MONEY, 7: PCT, 8: MONEY, 9: MONEY, 10: PCT}, widths={2: 26})
    ws.cell(len(rows) + 3, 1, f"Rule: urban or urban-expansion parcels of at least "
                              f"{config.base()['subdivision_min_m2']:,} m2 are subdivided; the rest are sold whole.")


def _memos(ws, memos):
    rows = [[m["id"], (m.get("recommendation") or "").replace("_", " "), m["status"], m.get("headline", ""),
             m.get("thesis", ""), "\n".join(f"- {r}" for r in m.get("risks", [])),
             "\n".join(f"- {c}" for c in m.get("conditions", []))] for m in memos]
    _table(ws, ["Id", "Recommendation", "Number check", "Headline", "Thesis", "Risks", "Conditions"], rows,
           widths={2: 22, 3: 14, 4: 50, 5: 80, 6: 60, 7: 50})
    for i in range(2, len(rows) + 2):
        for j in range(1, 8):
            ws.cell(i, j).alignment = Alignment(wrap_text=True, vertical="top")
