"""Command line.

  python -m land_deals generate                 synthetic portfolio (same as generate_data.py)
  python -m land_deals run [--demo|--live]      model + scenarios + sensitivity + AI memos -> workbook, dashboard, PDF
  python -m land_deals intake FILE [--accept]   AI turns a free-text parcel description into premises
  python -m land_deals demo [--live]            generate -> intake examples -> run
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import charts, config, findings, intake, memo, model, synthetic, workbook
from .llm import LLM, BudgetExceeded, NoRecording


def _llm(args) -> LLM:
    mode = "demo" if getattr(args, "demo", False) else ("live" if getattr(args, "live", False) else "auto")
    return LLM(mode=mode, max_calls=getattr(args, "max_calls", config.MAX_CALLS_PER_RUN))


def run_all(llm: LLM | None) -> dict:
    parcels = synthetic.load()
    pf = model.portfolio(parcels)
    scen, sens, strat = model.scenarios(parcels), model.sensitivity(parcels), model.strategy_comparison(parcels)
    memos = []
    for p in pf["projects"]:
        try:
            memos.append(memo.write(llm, p) if llm else {"id": p["id"], "status": "not generated", "facts": {}})
        except (NoRecording, BudgetExceeded) as e:
            memos.append({"id": p["id"], "status": f"not generated ({type(e).__name__})", "facts": {}})
    out = {
        "workbook": workbook.build(config.OUTPUT / "land_portfolio.xlsx", parcels, pf, scen, sens, strat, memos,
                                   findings.conclusions(pf, scen, sens, strat)),
        "dashboard": charts.dashboard(config.OUTPUT / "dashboard.html", pf, scen, sens, strat, memos),
        "pdf": charts.pdf_report(config.REPORTS / "final-report.pdf", pf, scen, sens, strat, memos),
        "charts": charts.save_pngs(pf, scen, sens, config.REPORTS / "charts"),
    }
    summary = {
        "parcels": len(parcels), "vgv": round(pf["vgv"]), "vgv_by_strategy": {k: round(v) for k, v in pf["vgv_by_strategy"].items()},
        "profit": round(pf["profit"]), "margin": round(pf["margin"], 4), "npv": round(pf["npv"]),
        "irr": None if pf["irr"] is None else round(pf["irr"], 4), "max_exposure": round(pf["max_exposure"]),
        "exposure_month": workbook.month_label(pf["exposure_month"]),
        "payback_month": workbook.month_label(pf["payback_month"]) if pf["payback_month"] is not None else None,
        "scenarios": [{k: (round(v, 4) if isinstance(v, float) else v) for k, v in s.items() if k != "overrides"} for s in scen],
        "memos": {m["id"]: {"recommendation": m.get("recommendation"), "status": m["status"]} for m in memos},
    }
    config.REPORTS.mkdir(exist_ok=True)
    (config.REPORTS / "summary.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False), encoding="utf-8")
    (config.REPORTS / "memos.md").write_text(memos_md(memos), encoding="utf-8")
    return {"summary": summary, "files": {k: (v.relative_to(config.ROOT).as_posix() if isinstance(v, Path)
                                              else [x.relative_to(config.ROOT).as_posix() for x in v])
                                          for k, v in out.items()}}


def memos_md(memos: list[dict]) -> str:
    lines = ["# Investment memos", "", "Written by Claude from the facts the model computed; every number was checked "
             "against those facts before being kept. Synthetic data generated by generate_data.py.", ""]
    for m in memos:
        lines += [f"## {m['facts'].get('parcel', m['id'])}", "", f"Recommendation: **{m.get('recommendation', '-')}** "
                  f"(number check: {m['status']})", ""]
        if m.get("headline"):
            lines += [f"**{m['headline']}**", "", m["thesis"], "", "Risks:"] + [f"- {r}" for r in m["risks"]]
            if m.get("conditions"):
                lines += ["", "Conditions:"] + [f"- {c}" for c in m["conditions"]]
            lines.append("")
    return "\n".join(lines)


def show_intake(res: dict) -> None:
    print(f"{res['file']}:")
    for k, v in res["parcel"].items():
        if k != "overrides":
            src = res["source"].get(k.replace("_m2", "") if k == "area_m2" else k, "")
            print(f"   {k:18} {v!s:>14}  {src}  {res['quotes'].get('area' if k == 'area_m2' else k, '')!r}")
    for pr in res["problems"]:
        print(f"   PROBLEM: {pr}")
    if res["notes"]:
        print(f"   note: {res['notes']}")


def main(argv=None) -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    p = argparse.ArgumentParser(prog="land_deals", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("generate")
    for name in ("run", "intake", "demo"):
        sp = sub.add_parser(name)
        g = sp.add_mutually_exclusive_group()
        g.add_argument("--demo", action="store_true", help="replay recorded answers only (no API call)")
        g.add_argument("--live", action="store_true", help="require an API key")
        sp.add_argument("--max-calls", type=int, default=config.MAX_CALLS_PER_RUN)
        if name == "run":
            sp.add_argument("--no-memos", action="store_true", help="skip the AI memos (no API call at all)")
        if name == "intake":
            sp.add_argument("file")
            sp.add_argument("--accept", action="store_true", help="add the parcel to data/portfolio.json")
    args = p.parse_args(argv)

    if args.cmd == "generate":
        print(json.dumps(synthetic.generate(), ensure_ascii=False, indent=1))
        return
    llm = _llm(args)
    try:
        if args.cmd == "intake":
            res = intake.run(llm, Path(args.file))
            show_intake(res)
            if args.accept:
                print("added:", json.dumps(intake.accept(res), ensure_ascii=False))
            else:
                print("   (review the values; run again with --accept to add the parcel to the portfolio)")
        elif args.cmd == "run":
            print(json.dumps(run_all(None if args.no_memos else llm), indent=1, ensure_ascii=False))
        elif args.cmd == "demo":
            print("1. generate the synthetic portfolio")
            synthetic.generate()
            print("2. AI intake of the free-text examples (shown for confirmation, not added)")
            for f in sorted(config.INTAKE.glob("*.txt")):
                try:
                    show_intake(intake.run(llm, f))
                except (NoRecording, BudgetExceeded) as e:
                    print(f"   {f.name}: skipped ({e})")
            print("3. model, scenarios, sensitivity, AI memos and outputs")
            print(json.dumps(run_all(llm), indent=1, ensure_ascii=False))
    finally:
        print("LLM summary:", json.dumps(llm.summary()))
